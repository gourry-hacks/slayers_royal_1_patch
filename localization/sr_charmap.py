def build_charmap() -> dict[int, str]:
    mapping: dict[int, str] = {}
    for index, char in enumerate(HIRAGANA, 1):
        mapping[index] = char
    for index, char in enumerate(KATAKANA, 0x51):
        mapping[index] = char

    mapping.update(
        {
            0x00A1: ",",
            0x00A2: ".",
            0x00A3: '"',
            0x00A4: "-",
            0x00A5: "=",
            0x00A6: "!",
            0x00A7: "?",
            0x00B2: "(",
            0x00B3: ")",
            0x00B4: "heart",
            0x00B5: "music",
            0x00B6: "spade",
            0x00B7: "!?",
            0x00B8: "middle-dot",
            0x00B9: "~",
            0x00BA: "B",
            0x00BB: "/",
            0x00BC: ":",
            0x00BD: ";",
        }
    )
    for value in range(10):
        mapping[0x00A8 + value] = str(value)

    for index, char in enumerate(KANJI_BANK0, 0x00C0):
        mapping[index] = char
    mapping.update(KANJI_GLYPHS)
    return mapping


CHARMAP = build_charmap()
